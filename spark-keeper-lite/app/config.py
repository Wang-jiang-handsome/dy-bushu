"""运行配置：全部来自环境变量，带安全默认值。

设计原则
--------
* **零依赖**：只用标准库，容器里 ``python main.py serve`` 直接能跑。
* **不写死密钥**：``SK_SECRET`` 未设置时，自动在 ``data/secret.key`` 生成并复用，
  避免「默认密钥上线」这种最容易被利用的漏洞；同时支持显式注入（Docker secrets）。
* **开发/生产可辨**：``SK_ENV=prod`` 会关掉调试信息、强制要求显式密钥。
"""

from __future__ import annotations

import os
import secrets
import sys
from dataclasses import dataclass, field
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent.parent      # 代码与数据目录（app/ 的上一级）
DEFAULT_DATA_DIR = BASE_DIR / "data"


def _detect_project_dir(base: Path) -> Path:
    """推导「项目根」——也就是 ``web/static`` 所在的那一层。

    两种布局都要支持（这是实测踩过的坑，交付目录里会把整个前端指错到父目录）：
    * **开发树**：``spark-shared/backend/app/config.py`` → 前端在 ``spark-shared/web/static``
      ⇒ 项目根 = ``BASE_DIR.parent``
    * **交付树**：``spark-keeper-pro/app/config.py`` → 前端在 ``spark-keeper-pro/web/static``
      ⇒ 项目根 = ``BASE_DIR`` 本身（后端就在包根，没有 backend 子目录）

    判定依据是「哪一层真的有 web/static」；两个都没有时回退开发树约定，
    保证行为可预期。仍可用 ``SK_PROJECT_DIR`` 显式覆盖（优先级最高）。
    """
    candidates = (base.parent, base)
    for candidate in candidates:
        if (candidate / "web" / "static").is_dir():
            return candidate
    return base.parent


PROJECT_DIR = _detect_project_dir(BASE_DIR)


def _env(key: str, default: str = "") -> str:
    value = os.environ.get(key)
    return default if value is None else value.strip()


def _env_int(key: str, default: int) -> int:
    raw = _env(key)
    if not raw:
        return default
    try:
        return int(raw)
    except ValueError:
        return default


def _env_float(name: str, default: float) -> float:
    raw = os.environ.get(name)
    if raw is None or str(raw).strip() == "":
        return float(default)
    try:
        return float(str(raw).strip())
    except (TypeError, ValueError):
        return float(default)


def _env_bool(key: str, default: bool = False) -> bool:
    raw = _env(key).lower()
    if raw in ("1", "true", "yes", "on"):
        return True
    if raw in ("0", "false", "no", "off"):
        return False
    return default


def _load_or_create_secret(data_dir: Path, env_value: str) -> tuple[str, bool]:
    """返回 (密钥, 是否为自动生成)。"""
    if env_value:
        return env_value, False
    data_dir.mkdir(parents=True, exist_ok=True)
    key_file = data_dir / "secret.key"
    if key_file.exists():
        raw = key_file.read_text(encoding="utf-8").strip()
        if len(raw) >= 32:
            return raw, False
    key = secrets.token_urlsafe(48)
    key_file.write_text(key, encoding="utf-8")
    try:  # 尽力收紧权限（Windows 上无效但不报错）
        os.chmod(key_file, 0o600)
    except OSError:
        pass
    return key, True


@dataclass
class Settings:
    # --- 基础 ---
    env: str = "dev"
    host: str = "0.0.0.0"
    port: int = 8000
    base_dir: Path = BASE_DIR
    data_dir: Path = DEFAULT_DATA_DIR
    public_url: str = ""          # 反代后的对外地址，用于支付回调拼接
    trusted_proxies: tuple[str, ...] = ()
    project_dir: Path = PROJECT_DIR

    # --- 数据库 ---
    db_path: Path = DEFAULT_DATA_DIR / "spark.db"
    db_busy_timeout_ms: int = 8000

    # --- 安全 ---
    secret: str = ""
    secret_autogenerated: bool = False
    access_token_ttl: int = 2 * 60 * 60          # 秒
    refresh_token_ttl: int = 14 * 24 * 60 * 60
    max_login_fail: int = 8                       # 连续失败次数
    login_lock_seconds: int = 600                 # 锁定时长
    rate_limit_per_minute: int = 240              # 单 IP 每分钟请求上限（0 = 关闭）
    bootstrap_admin_user: str = "admin"
    bootstrap_admin_email: str = ""

    # --- 站点 ---
    timezone: str = "Asia/Shanghai"

    # --- 邮件 / 短信 ---
    smtp_host: str = ""
    smtp_port: int = 465
    smtp_user: str = ""
    smtp_password: str = ""
    smtp_from: str = ""
    smtp_ssl: bool = True
    sms_provider: str = ""                        # 空 = 不发送，仅把验证码写日志（开发用）
    sms_access_key: str = ""
    sms_secret_key: str = ""
    sms_sign: str = ""
    sms_template: str = ""

    # --- 自动化（Chrome/CDP）---
    chrome_path: str = ""                         # 空 = 自动探测 Edge/Chrome
    browser_headless: bool = True
    browser_width: int = 1366
    browser_height: int = 900
    # 单次页面操作的超时（秒）。真实事故：容器 CPU 被限流时，连
    # ``Runtime.evaluate('location.href')`` 都可能超过 10 秒 → 诊断/发送全失败。
    # 默认给 30 秒，弱机器可在 .env 里调大（SK_CDP_PAGE_TIMEOUT=45）。
    cdp_page_timeout: float = 30.0
    # 低配模式：少开光栅线程、关掉软件 WebGL 等，专门给 1~2 核小机器用。
    # 小机器上抖音私信页很重，这些优化能显著降低"渲染进程假死"的概率。
    chrome_low_resource: bool = False
    # Chromium 沙箱开关："auto" = 以 root 或在容器里自动关掉沙箱；
    # "1" = 强制关（--no-sandbox）；"0" = 强制开。
    # 为什么要这个：容器（尤其宿主机是老内核 CentOS 7，未启用 user namespace）
    # 里 Chromium 起不来，报 "No usable sandbox!"，只能关沙箱。
    chrome_no_sandbox: str = "auto"
    max_concurrent_browsers: int = 2
    task_timeout_seconds: int = 180
    task_retry_backoff: int = 60
    session_root: Path = DEFAULT_DATA_DIR / "sessions"
    screenshot_root: Path = DEFAULT_DATA_DIR / "screenshots"
    demo_mode: bool = False                       # 1 = 不真的开浏览器（演示/CI）
    # 以下四项由自动化引擎按需读取；暴露成环境变量是为了让部署者不用改代码。
    # 注意：**0 是合法值**（例如 0 = 关闭登录态 TTL），所以读取时必须写成
    # `int(getattr(settings, "x", D) if getattr(settings, "x", None) is not None else D)`，
    # 不能用 `getattr(...) or D`（那会把合法的 0 静默换成默认值，本会话踩过 4 次）。
    session_ttl_days: int = 30                    # 登录态本地缓存有效期（天）
    login_timeout_seconds: int = 180              # 扫码/短信登录整段超时（秒）
    # 等二维码出现的最长时间（秒）。实机实测：页面加载 + 弹层渲染 + 二维码替换占位图
    # 合计要 10~20 秒，30 秒在慢机上会误报「没找到二维码」，所以默认给 60。
    qrcode_wait_seconds: int = 60
    # 每日执行次数是否「无限」。自托管单租户默认 True：套餐/次数只是商业化外壳，
    # 自己用不该被每日次数卡住。设 SK_UNLIMITED_TASK_RUNS=0 可恢复按套餐计次。
    unlimited_task_runs: bool = True
    demo_step_seconds: float = 1.0                # 演示模式每步耗时（秒），调小可加速 CI
    worker_autostart: bool = True                 # 启动 Web 时自动起 worker 线程池
    # 生产环境允许跨域访问的来源白名单（逗号分隔，如 https://app.example.com）。
    # 用途：把**前端静态文件**放到 CDN/Netlify 之类的静态托管，后端仍跑在有
    # Python + Chromium 的服务器上。默认空 = 不开跨域（同源部署最安全）。
    cors_origins: tuple[str, ...] = ()

    # --- 调度 ---
    scheduler_enabled: bool = True
    scheduler_tick_seconds: int = 20
    worker_id: str = ""
    # 日志/会话/验证码保留天数（调度器每天清理一次；0 = 不清理）
    log_keep_days: int = 30

    @property
    def static_dir(self) -> Path:
        """前端构建产物目录（index.html 所在处）。"""
        return self.project_dir / "web" / "static"

    @property
    def is_prod(self) -> bool:
        return self.env.lower() in ("prod", "production")

    # 静态站点目录（前端 bundle 与上传文件）
    upload_dir: Path = DEFAULT_DATA_DIR / "uploads"

    def ensure_dirs(self) -> None:
        for path in (
            self.data_dir,
            self.session_root,
            self.screenshot_root,
            self.upload_dir,
        ):
            path.mkdir(parents=True, exist_ok=True)

    def public_base_url(self, fallback_host: str = "127.0.0.1:8000") -> str:
        if self.public_url:
            return self.public_url.rstrip("/")
        if not fallback_host:
            fallback_host = "127.0.0.1:8000"
        return f"http://{fallback_host}".rstrip("/")

    def warnings(self) -> list[str]:
        out: list[str] = []
        if self.secret_autogenerated and self.is_prod:
            out.append(
                "SK_SECRET 未设置，已自动生成 data/secret.key；生产环境建议显式注入密钥，"
                "否则容器重建后旧 token 全部失效。"
            )
        if self.env == "dev" and self.host == "0.0.0.0":
            out.append("开发模式监听 0.0.0.0，公网部署请务必置于 HTTPS 反向代理之后。")
        return out


def load_settings(env_file: Path | None = None, overrides: dict | None = None) -> Settings:
    """读取环境变量（可先加载 .env），返回 Settings。

    .env 只在「环境变量本身不存在」时生效，方便命令行覆盖。
    """
    if env_file and env_file.exists():
        for line in env_file.read_text(encoding="utf-8").splitlines():
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            key = key.strip()
            value = value.strip().strip('"').strip("'")
            if key and key not in os.environ:
                os.environ[key] = value

    data_dir = Path(_env("SK_DATA_DIR") or str(DEFAULT_DATA_DIR)).expanduser()
    secret, generated = _load_or_create_secret(data_dir, _env("SK_SECRET"))

    cfg = Settings(
        env=_env("SK_ENV", "dev"),
        host=_env("SK_HOST", "0.0.0.0"),
        port=_env_int("SK_PORT", 8000),
        base_dir=BASE_DIR,
        project_dir=Path(_env("SK_PROJECT_DIR") or str(PROJECT_DIR)),
        data_dir=data_dir,
        public_url=_env("SK_PUBLIC_URL"),
        trusted_proxies=tuple(
            p.strip() for p in _env("SK_TRUSTED_PROXIES").split(",") if p.strip()
        ),
        db_path=Path(_env("SK_DB_PATH") or str(data_dir / "spark.db")),
        db_busy_timeout_ms=_env_int("SK_DB_BUSY_TIMEOUT_MS", 8000),
        secret=secret,
        secret_autogenerated=generated,
        access_token_ttl=_env_int("SK_ACCESS_TTL", 2 * 60 * 60),
        refresh_token_ttl=_env_int("SK_REFRESH_TTL", 14 * 24 * 60 * 60),
        max_login_fail=_env_int("SK_MAX_LOGIN_FAIL", 8),
        login_lock_seconds=_env_int("SK_LOGIN_LOCK_SECONDS", 600),
        rate_limit_per_minute=_env_int("SK_RATE_LIMIT_PER_MINUTE", 240),
        bootstrap_admin_user=_env("SK_ADMIN_USER", "admin"),
        bootstrap_admin_email=_env("SK_ADMIN_EMAIL"),
        timezone=_env("SK_TIMEZONE", "Asia/Shanghai"),
        smtp_host=_env("SK_SMTP_HOST"),
        smtp_port=_env_int("SK_SMTP_PORT", 465),
        smtp_user=_env("SK_SMTP_USER"),
        smtp_password=_env("SK_SMTP_PASSWORD"),
        smtp_from=_env("SK_SMTP_FROM"),
        smtp_ssl=_env_bool("SK_SMTP_SSL", True),
        sms_provider=_env("SK_SMS_PROVIDER"),
        sms_access_key=_env("SK_SMS_ACCESS_KEY"),
        sms_secret_key=_env("SK_SMS_SECRET_KEY"),
        sms_sign=_env("SK_SMS_SIGN"),
        sms_template=_env("SK_SMS_TEMPLATE"),
        chrome_path=_env("SK_CHROME_PATH"),
        browser_headless=_env_bool("SK_BROWSER_HEADLESS", True),
        chrome_no_sandbox=str(os.environ.get("SK_CHROME_NO_SANDBOX", "auto") or "auto").strip() or "auto",
        cdp_page_timeout=_env_float("SK_CDP_PAGE_TIMEOUT", 30.0),
        chrome_low_resource=_env_bool("SK_CHROME_LOW_RESOURCE", False),
        # 每日执行次数不限（自托管默认开；SK_UNLIMITED_TASK_RUNS=0 可关）
        unlimited_task_runs=_env_bool("SK_UNLIMITED_TASK_RUNS", True),
        browser_width=_env_int("SK_BROWSER_WIDTH", 1366),
        browser_height=_env_int("SK_BROWSER_HEIGHT", 900),
        max_concurrent_browsers=_env_int("SK_MAX_CONCURRENT_BROWSERS", 2),
    # 跨域白名单：SK_CORS_ORIGINS="https://a.com,https://b.com"（空=不开）
    cors_origins=tuple(
        item.strip().rstrip("/")
        for item in str(os.environ.get("SK_CORS_ORIGINS", "")).split(",")
        if item.strip()
    ),
        task_timeout_seconds=_env_int("SK_TASK_TIMEOUT", 180),
        task_retry_backoff=_env_int("SK_TASK_RETRY_BACKOFF", 60),
        session_root=Path(_env("SK_SESSION_DIR") or str(data_dir / "sessions")),
        screenshot_root=Path(_env("SK_SCREENSHOT_DIR") or str(data_dir / "screenshots")),
        upload_dir=Path(_env("SK_UPLOAD_DIR") or str(data_dir / "uploads")),
        demo_mode=_env_bool("SK_DEMO_MODE", False),
        scheduler_enabled=_env_bool("SK_SCHEDULER_ENABLED", True),
        scheduler_tick_seconds=_env_int("SK_SCHEDULER_TICK", 20),
        log_keep_days=_env_int("SK_LOG_KEEP_DAYS", 30),
        worker_id=_env("SK_WORKER_ID") or f"w-{os.getpid()}",
    )
    if overrides:
        for key, value in overrides.items():
            setattr(cfg, key, value)
    return cfg


_settings: Settings | None = None


def get_settings() -> Settings:
    global _settings
    if _settings is None:
        _settings = load_settings(BASE_DIR / ".env")
    return _settings


def set_settings(cfg: Settings) -> None:
    global _settings
    _settings = cfg


def debug(msg: str) -> None:
    if get_settings().env == "dev":
        print(f"[debug] {msg}", file=sys.stderr, flush=True)
