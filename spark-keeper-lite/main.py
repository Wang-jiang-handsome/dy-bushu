"""命令行入口与服务器启动脚本。

用法
----
    python main.py init                     # 建库、写种子数据、创建管理员
    python main.py serve [--port 8000]      # 启动 Web 服务（含调度器）
    python main.py worker                   # 只跑调度器，不起 Web（适合单独容器）
    python main.py migrate                  # 只执行数据库迁移
    python main.py admin --username admin   # 创建/重置管理员
    python main.py card --days 30 --count 10 --package monthly
    python main.py task --account-id 3      # 手动跑一次续火花（命令行调试用）
    python main.py check                    # 环境体检
    python main.py diagnose --account-id 3  # 导出页面结构（抖音改版时排障）
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
if str(BASE_DIR) not in sys.path:
    sys.path.insert(0, str(BASE_DIR))

from app import bootstrap as boot                      # noqa: E402
from app.config import get_settings, load_settings, set_settings  # noqa: E402
from app.version import BUILD, PRODUCT, VERSION        # noqa: E402


def _print_banner() -> None:
    print(f"  {PRODUCT}  v{VERSION} (build {BUILD})")
    print("  " + "-" * 52)


def cmd_init(args) -> int:
    _print_banner()
    settings = get_settings()
    report = boot.init_app(settings, quiet=False)
    boot.seed_site_configs()
    created, secret = boot.ensure_admin(
        settings,
        username=args.username or "",
        password=args.password or "",
        email=args.email or "",
    )
    print(f"  数据目录：{report['data_dir']}")
    print(f"  数据库：  {report['db_path']}")
    print(f"  路由：    {report['routes']} 条")
    print("  初始化完成，执行 `python main.py serve` 启动服务。")
    return 0


def cmd_serve(args) -> int:
    from app.http_server import serve

    settings = get_settings()
    if args.port:
        settings.port = int(args.port)
    if args.host:
        settings.host = args.host
    if args.no_scheduler:
        settings.scheduler_enabled = False
    _print_banner()
    if settings.scheduler_enabled:
        from app.worker.scheduler import start_background

        start_background(settings)
        print("  调度器已启动（每 "
              f"{settings.scheduler_tick_seconds}s 检查一次到期任务）")
    else:
        print("  调度器已关闭（--no-scheduler）")
    serve(settings, open_browser=args.open)
    return 0


def cmd_worker(args) -> int:
    from app.worker.scheduler import run_forever

    _print_banner()
    settings = get_settings()
    print("  仅调度器模式（不起 Web 服务）")
    run_forever(settings)
    return 0


def cmd_migrate(args) -> int:
    from app import db

    applied = db.migrate(verbose=True)
    print(f"  迁移完成，本次应用 {len(applied)} 个：{', '.join(applied) or '无'}")
    return 0


def cmd_admin(args) -> int:
    settings = get_settings()
    boot.init_app(settings, quiet=True)
    created, secret = boot.ensure_admin(
        settings,
        username=args.username or "",
        password=args.password or "",
        email=args.email or "",
        silent=False,
    )
    return 0


def cmd_card(args) -> int:
    from app.api.cardkeys import generate_cards

    boot.init_app(get_settings(), quiet=True)
    result = generate_cards(
        package_code=args.package,
        card_type=args.type,
        days=args.days,
        count=args.count,
        use_limit=args.use_limit,
        amount_cents=args.amount,
        batch_note=args.note or "命令行生成",
        created_by=None,
    )
    print(f"  批次号：{result['batch_no']}（共 {result['count']} 张）")
    for code in result["codes"]:
        print(f"  {code}")
    return 0


def cmd_task(args) -> int:
    from app.worker.runner import run_task_now

    boot.init_app(get_settings(), quiet=True)
    outcome = run_task_now(account_id=int(args.account_id), trigger_type="manual",
                           dry_run=bool(args.dry_run))
    print(f"  执行结果：{outcome.get('status')}  成功 {outcome.get('success_count')} / "
          f"失败 {outcome.get('fail_count')}")
    if outcome.get("message"):
        print(f"  说明：{outcome['message']}")
    return 0 if outcome.get("status") in ("success", "partial") else 1


def cmd_check(args) -> int:
    settings = get_settings()
    report = boot.check_cloud_environment()
    _print_banner()
    for key, value in report.items():
        print(f"  {key:<20} {value}")
    print("  " + "-" * 52)
    if report["browser_found"]:
        print("  浏览器：可用")
    else:
        print("  [警告] 未找到 Chrome/Edge，自动续火花需要它。")
        print("         Linux 示例：apt-get install -y chromium")
    if not report["tzdata_ok"]:
        print("  [警告] 时区库不可用，将退回固定 +08:00 偏移。")
    if settings.secret_autogenerated:
        print("  [提示] SK_SECRET 未配置，已自动生成 data/secret.key。")
    # 解释器能力缺失（最典型是缺 _ssl）：不是配置问题，装残了就得换 Python
    problems = boot.runtime_problems()
    if problems:
        print("  " + "-" * 52)
        print("  [严重] 当前 Python 解释器缺少关键模块：")
        for item in problems:
            print(f"    - {item}")
        print("  修法：换用自带 OpenSSL 的 Python（uv python install 3.11）、")
        print("        或装 openssl-devel 后重装 Python、或直接用 Docker。")
        return 1
    return 0


def cmd_diagnose(args) -> int:
    from app.automation.diagnostics import diagnose_account

    boot.init_app(get_settings(), quiet=True)
    result = diagnose_account(int(args.account_id), out_dir=args.out)

    # 关键：**必须把失败原因打印出来**。旧实现无论成功失败都只打一行「诊断输出目录」，
    # 用户拿到的是空目录 + 没有任何提示，等于白跑（扫码失败时最需要这份报告）。
    message = str(result.get("message") or "")
    if not result.get("ok"):
        print(f"  ✗ 诊断没有完成：{message or '未知原因'}")
        if result.get("out_dir"):
            print(f"    输出目录：{result['out_dir']}")
        return 1

    if result.get("out_dir"):
        print(f"  诊断输出目录：{result['out_dir']}")
    if message:
        print(f"  说明：{message}")
    selectors_result = result.get("selectors") or {}
    if not selectors_result:
        print("  （没有选择器数据）")
    hit_groups = 0
    for name, info in selectors_result.items():
        visible = int((info or {}).get("visible") or 0)
        total = int((info or {}).get("total") or 0)
        if visible:
            hit_groups += 1
        print(f"  {name:<22} 命中 {total} 个 / 可见 {visible} 个")
    files = result.get("files") or []
    if files:
        print(f"  已导出 {len(files)} 个文件（含截图与 HTML 报告，可直接发给开发者排障）")
    if not hit_groups:
        print("  ⚠ 所有选择器都没有可见命中：抖音页面结构可能已改版，请把报告发出来校准")
    if getattr(args, "print_report", False):
        _print_diagnose_summary(result)
    return 0


def _print_diagnose_summary(result: dict) -> None:
    """把排障最需要的信息打到终端（服务器上取文件不方便时用）。

    内容刻意保持「短且自解释」：环境（Python/SQLite/是否容器/浏览器路径）、
    登录态、页面取证（标题/readyState/会话条数/正文片段/阻塞类型）、
    选择器命中情况、错误原因。用户复制这一段发出来就够定位问题。
    """
    import json as _json
    import sqlite3 as _sqlite3

    from app.automation import cdp as _cdp
    from app.automation import chrome as _chrome
    from app.config import get_settings as _get_settings

    settings = _get_settings()
    report: dict = {}
    out_dir = str(result.get("out_dir") or "")
    if out_dir:
        import pathlib as _pathlib

        candidate = _pathlib.Path(out_dir) / "report.json"
        if candidate.is_file():
            try:
                report = _json.loads(candidate.read_text(encoding="utf-8"))
            except Exception:                    # noqa: BLE001
                report = {}

    env = {
        "python": sys.version.split()[0],
        "sqlite": getattr(_sqlite3, "sqlite_version", "?"),
        "container": _cdp.in_container(),
        "display": _cdp.display_available(),
        "chrome_no_sandbox": str(getattr(settings, "chrome_no_sandbox", "auto")),
        "headless": bool(getattr(settings, "browser_headless", True)),
        "browser": "",
    }
    try:
        env["browser"] = _chrome.find_browser(getattr(settings, "chrome_path", "") or "") or ""
    except Exception:                            # noqa: BLE001
        env["browser"] = ""

    extra = (report.get("extra") or {}) if isinstance(report, dict) else {}
    snapshot = extra.get("snapshot") or {}
    body = " ".join(str(snapshot.get("body") or "").split())[:200]

    print("")
    print("  ===== 复制下面这段发给开发者（排障摘要） =====")
    print(f"  环境     python={env['python']} sqlite={env['sqlite']} "
          f"容器={env['container']} 图形界面={env['display']}")
    print(f"          浏览器={env['browser'] or '(未找到)'} "
          f"headless={env['headless']} no_sandbox={env['chrome_no_sandbox']}")
    print(f"  结果     ok={result.get('ok')} message={result.get('message')}")
    print(f"  登录态   logged_in={extra.get('logged_in')} reason={extra.get('login_reason')}")
    print(f"  私信页   ok={extra.get('messages_ok')} reason={extra.get('messages_reason')}")
    print(f"  页面     url={extra.get('url')}")
    print(f"           title={extra.get('title')!r} 阻塞={snapshot.get('wall') or '无'} "
          f"会话={snapshot.get('conversations')} 输入框={snapshot.get('editors')}")
    if body:
        print(f"           正文=«{body}»")
    if extra.get("error"):
        print(f"  错误     {extra.get('error')}")
    hits = {k: v for k, v in (result.get("selectors") or {}).items()
            if int((v or {}).get("visible") or 0) > 0}
    print(f"  选择器   命中组 {len(hits)} 个：{', '.join(hits) or '(无)'}")
    for name, info in list(hits.items())[:8]:
        print(f"           {name}: visible={info.get('visible')} "
              f"sample={str(info.get('sample') or '')[:60]!r}")
    print(f"  输出目录 {out_dir or '(无)'}")
    print(f"  文件     {', '.join(result.get('files') or []) or '(无)'}")
    print("  ===== 摘要结束 =====")
    print("")


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="main.py",
        description=f"{PRODUCT} v{VERSION} —— 自托管抖音续火花系统",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog=__doc__,
    )
    parser.add_argument("--env-file", default="", help="指定 .env 文件路径")
    sub = parser.add_subparsers(dest="command")

    p_init = sub.add_parser("init", help="初始化数据库与管理员")
    p_init.add_argument("--username", help="管理员用户名（默认 admin）")
    p_init.add_argument("--password", help="管理员密码（不传则随机生成并打印）")
    p_init.add_argument("--email", help="管理员邮箱")
    p_init.set_defaults(func=cmd_init)

    p_serve = sub.add_parser("serve", help="启动 Web 服务")
    p_serve.add_argument("--host", help="监听地址（默认 0.0.0.0）")
    p_serve.add_argument("--port", type=int, help="监听端口（默认 8000）")
    p_serve.add_argument("--open", action="store_true", help="启动后自动打开浏览器")
    p_serve.add_argument("--no-scheduler", action="store_true", help="不启动内置调度器")
    p_serve.set_defaults(func=cmd_serve)

    p_worker = sub.add_parser("worker", help="只运行调度器（不起 Web）")
    p_worker.set_defaults(func=cmd_worker)

    p_migrate = sub.add_parser("migrate", help="执行数据库迁移")
    p_migrate.set_defaults(func=cmd_migrate)

    p_admin = sub.add_parser("admin", help="创建或重置管理员")
    p_admin.add_argument("--username")
    p_admin.add_argument("--password")
    p_admin.add_argument("--email")
    p_admin.set_defaults(func=cmd_admin)

    p_card = sub.add_parser("card", help="批量生成卡密")
    p_card.add_argument("--package", default="monthly", help="套餐 code（默认 monthly）")
    p_card.add_argument("--type", default="time", choices=("time", "count", "balance"))
    p_card.add_argument("--days", type=int, default=30)
    p_card.add_argument("--count", type=int, default=10)
    p_card.add_argument("--use-limit", type=int, default=1, dest="use_limit")
    p_card.add_argument("--amount", type=int, default=0, help="余额卡面额（分）")
    p_card.add_argument("--note", default="")
    p_card.set_defaults(func=cmd_card)

    p_task = sub.add_parser("task", help="立即执行一次指定账号的续火花任务")
    p_task.add_argument("--account-id", type=int, required=True)
    p_task.add_argument("--dry-run", action="store_true", help="只探测好友，不发送")
    p_task.set_defaults(func=cmd_task)

    p_check = sub.add_parser("check", help="环境体检")
    p_check.set_defaults(func=cmd_check)

    p_diag = sub.add_parser("diagnose", help="导出抖音页面结构（排障）")
    p_diag.add_argument("--account-id", type=int, required=True)
    p_diag.add_argument("--out", default="")
    # 远程服务器上不方便取文件时，用它把「开发者需要的证据」直接打到终端，复制粘贴即可
    p_diag.add_argument("--print", dest="print_report", action="store_true",
                        help="打印可复制的报告摘要（页面取证/选择器命中/错误原因）")
    p_diag.set_defaults(func=cmd_diagnose)

    return parser


def main(argv: list[str] | None = None) -> int:
    from app.common import timeutil  # noqa: F401  触发时区初始化

    parser = build_parser()
    args = parser.parse_args(argv)
    if not getattr(args, "command", None):
        parser.print_help()
        return 0
    env_file = Path(args.env_file) if args.env_file else BASE_DIR / ".env"
    set_settings(load_settings(env_file))
    try:
        return int(args.func(args) or 0)
    except KeyboardInterrupt:
        print("\n  已中断")
        return 130
    except Exception as exc:      # noqa: BLE001 - CLI 顶层兜底，给出可读错误
        import traceback

        print(f"\n  [错误] {type(exc).__name__}: {exc}", file=sys.stderr)
        if os.environ.get("SK_DEBUG"):
            traceback.print_exc()
        return 1


if __name__ == "__main__":
    sys.exit(main())
